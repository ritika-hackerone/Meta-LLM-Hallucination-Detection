from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Optional

from loguru import logger

from pipeline.rag_retriever  import RAGRetriever
from pipeline.nli_classifier import NLIClassifier, NLIResult
from pipeline import meta_llm
import config


@dataclass
class VerificationResult:
    # Input
    question:           str
    response:           str

    # RAG
    retrieved_passages: List[str] = field(default_factory=list)
    retrieved_sources:  List[str] = field(default_factory=list)

    # NLI
    nli_result:         Optional[NLIResult] = None

    # Judge
    final_label:        str   = config.LABEL_UNCERTAIN
    confidence:         int   = 0
    explanation:        str   = ""

    # Was the response auto-generated by the student LLM?
    auto_generated:     bool  = False

    def to_dict(self) -> dict:
        return {
            "question":            self.question,
            "response":            self.response,
            "final_label":         self.final_label,
            "confidence":          self.confidence,
            "explanation":         self.explanation,
            "nli_label":           self.nli_result.label if self.nli_result else "N/A",
            "entailment_score":    self.nli_result.entailment_score if self.nli_result else 0,
            "contradiction_score": self.nli_result.contradiction_score if self.nli_result else 0,
            "retrieved_passages":  self.retrieved_passages,
            "retrieved_sources":   self.retrieved_sources,
            "auto_generated":      self.auto_generated,
        }


class VerifierPipeline:
    """
    End-to-end factual verification pipeline.

    Parameters
    ----------
    use_judge : bool
        If True (default), the Judge LLM refines the NLI verdict.
        Set False to skip the Gemini API call (NLI-only mode).
    """

    def __init__(self, use_judge: bool = True):
        logger.info("Initialising VerifierPipeline…")
        self.rag       = RAGRetriever()
        self.nli       = NLIClassifier()
        self.use_judge = use_judge
        logger.info("VerifierPipeline ready.")

    # ──────────────────────────────────────────────────────────

    def verify(
        self,
        question:        str,
        response:        str  = "",
        generate_answer: bool = False,
    ) -> VerificationResult:
        """
        Verify a *response* to *question*.

        Parameters
        ----------
        question        : The question being asked.
        response        : The LLM response to fact-check.
                          If empty and generate_answer=True, Gemini generates one first.
        generate_answer : Auto-generate a response via the student LLM.
        """
        result = VerificationResult(question=question, response=response)

        # ── Step 0: Optionally generate a response ────────────
        if generate_answer or not response.strip():
            logger.info("Step 0: Generating response with Student LLM (Gemini)…")
            result.response       = meta_llm.generate_answer(question)
            result.auto_generated = True

        # ── Step 1: RAG retrieval ──────────────────────────────
        logger.info("Step 1: Retrieving evidence via RAG…")
        passages, sources         = self.rag.retrieve(question)
        result.retrieved_passages = passages
        result.retrieved_sources  = sources

        # ── Step 2: NLI classification ─────────────────────────
        logger.info("Step 2: Running NLI classification…")
        nli_res           = self.nli.classify(result.response, passages)
        result.nli_result = nli_res

        # ── Step 3: Judge LLM (Gemini) ─────────────────────────
        if self.use_judge:
            logger.info("Step 3: Running Judge LLM (Gemini)…")
            verdict = meta_llm.judge_response(
                question     = question,
                response     = result.response,
                evidence     = nli_res.evidence_used,
                nli_label    = nli_res.label,
                entail_score = nli_res.entailment_score,
                contra_score = nli_res.contradiction_score,
            )
            result.final_label = verdict["label"]
            result.confidence  = verdict["confidence"]
            result.explanation = verdict["explanation"]
        else:
            # NLI-only mode — no API call needed
            result.final_label = nli_res.label
            result.confidence  = int(max(nli_res.entailment_score,
                                         nli_res.contradiction_score) * 100)
            result.explanation = nli_res.evidence_used or "Based on NLI scores only."

        logger.info(f"Verdict: {result.final_label} ({result.confidence}%)")
        return result




